#!/usr/bin/env bash
# The Homebrew cask for a release, from its checksums.txt, for the tap
# spendyard/homebrew-tap (Casks/spendyard.rb): brew install spendyard/tap/spendyard.
# The release workflow runs it.
#
#   scripts/homebrew.sh v0.1.0 dist/checksums.txt > Casks/spendyard.rb
#
# A cask, not a formula: a formula without a bottle counts as built from
# source, so Homebrew first insists on current Xcode Command Line Tools,
# though spendyard is already built; casks skip that. A third argument
# replaces where the archives are downloaded from, e.g. a file:// folder to
# try the cask before a release.
set -euo pipefail

tag="$1"
sums="$2"
base="${3:-https://github.com/spendyard/spendyard/releases/download/$tag}"

sum() {
  awk -v f="spendyard_$1.tar.gz" '$2 == f { print $1 }' "$sums"
}

for target in darwin_arm64 darwin_amd64 linux_arm64 linux_amd64; do
  [ -n "$(sum "$target")" ] || { echo "no spendyard_$target.tar.gz in $sums" >&2; exit 1; }
done

cat <<RUBY
# Generated by spendyard's release workflow (scripts/homebrew.sh); don't edit it by hand.
cask "spendyard" do
  version "${tag#v}"

  on_macos do
    on_arm do
      sha256 "$(sum darwin_arm64)"
      url "$base/spendyard_darwin_arm64.tar.gz"
    end

    on_intel do
      sha256 "$(sum darwin_amd64)"
      url "$base/spendyard_darwin_amd64.tar.gz"
    end
  end
  on_linux do
    on_arm do
      sha256 "$(sum linux_arm64)"
      url "$base/spendyard_linux_arm64.tar.gz"
    end

    on_intel do
      sha256 "$(sum linux_amd64)"
      url "$base/spendyard_linux_amd64.tar.gz"
    end
  end

  name "Spendyard"
  desc "Reads receipts and invoices and works out what you're paying for"
  homepage "https://spendyard.com/"

  livecheck do
    url :url
    strategy :github_latest
  end

  binary "spendyard"

  # spendyard isn't notarised yet: without this, Gatekeeper may stop the
  # downloaded binary on macOS. A postflight block, not postflight_steps
  # (Homebrew 6 and later), so Homebrew from 4.5 on reads the cask.
  postflight do
    if OS.mac?
      system_command "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "#{staged_path}/spendyard"]
    end
  end
end
RUBY
